// Indice del caracter en la tabla, o 0 (espacio) si no esta.
inline int fontIndex(char c) {
    if (c >= 'a' && c <= 'z') c = char(c - 'a' + 'A');  // solo hay mayusculas
    const char* set = fontCharset();
    for (int i = 0; set[i]; ++i) {
        if (set[i] == c) return i;
    }
    return 0;
}
