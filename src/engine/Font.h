// hexadecimal: una mascara de bits mal tecleada no se ve hasta que sale en
// pantalla, y ya seria tarde.
//
// Cada glifo son 7 bytes, uno por fila, con los 5 bits bajos usados. Ocupa
// menos de medio kilobyte, que en la ROM de la GBA es nada.

